"""Resolution-only contract: live vectors, bindings, validation and migration metadata."""
import copy
import hashlib
import json
from pathlib import Path
import sys
import unittest

PROJECT = Path(__file__).resolve().parents[1]
SHARED = PROJECT.parent / '_shared'
sys.path[:0] = [str(SHARED / 'engine'), str(SHARED / 'tooling')]
from treasures import TreasureCampaign, TreasureError, ResolutionError, validate_catalog
from treasure_resolution import definitions, configuration


class TreasureResolutionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.catalog = json.loads((PROJECT / 'scenario/treasures/age-of-sail.json').read_text())

    def test_live_vectors_cover_every_authored_identity_at_multiple_seeds(self):
        lines = ['// Headless SHA-256 namespaced vectors; regenerated by test_treasure_resolution.py.',
                 'package TreasureVectorsTests', '', 'import TreasureResolutionTests', '']
        for index, treasure in enumerate(self.catalog['treasures']):
            lines += ['@test', f'function authoredTreasureVector{index}()']
            for seed in (1, 4, 42):
                result = TreasureCampaign(self.catalog, seed).resolve(treasure['id'])
                expected = 'seeded,' + ','.join(result[key] or '' for key in (
                    'candidateLocationId', 'rewardVariantId', 'guardId', 'hazardId', 'encounterId'))
                lines.append(f'\ttreasureVector({index}, "{seed}", "{expected}")')
        self.assertEqual('\n'.join(lines) + '\n', (PROJECT / 'wurst/TreasureVectorsTests.wurst').read_text())
        tid = 'treasure_order_of_christ_archive'
        self.assertEqual('cand_templar_tomar', TreasureCampaign(self.catalog, 1).resolve(tid)['candidateLocationId'])
        self.assertEqual('cand_templar_almourol', TreasureCampaign(self.catalog, 4).resolve(tid)['candidateLocationId'])

    def test_generated_definitions_keep_authored_weights_restrictions_and_variants(self):
        locations = [dict(id=c['id'], kind='treasure', mapId=c['physicalMapId'],
                          world=[c['position']['x'], c['position']['y']], movements=[0])
                     for c in self.catalog['candidateLocations']]
        generated = definitions(self.catalog, locations)
        for source, actual in zip(self.catalog['candidateLocations'], generated['candidateLocations']):
            self.assertEqual(source, {k: v for k, v in actual.items() if k != 'placement'})
        for key in ('rewardPools', 'guards', 'hazards', 'encounters', 'clues'):
            self.assertEqual(self.catalog[key], generated[key])
        wurst = configuration(generated)
        self.assertIn('new RuntimeTreasure("treasure_order_of_christ_archive", "", "")', wurst)
        self.assertIn('.legacyLocationId = "cand_templar_tomar"', wurst)
        self.assertIn('.weight = 3', wurst)
        self.assertIn('.rewards.add("relic_and_coin", 3)', wurst)
        self.assertIn('.anchorRegions = "|europe|"', wurst)
        with self.assertRaises(ValueError):
            definitions(self.catalog, locations[1:])
        locations[0]['movements'] = []
        with self.assertRaises(ValueError):
            definitions(self.catalog, locations)

    def test_fallback_validates_authored_anchor_availability_and_exclusivity(self):
        catalog = copy.deepcopy(self.catalog)
        original = catalog['treasures'][0]
        duplicate = copy.deepcopy(original)
        duplicate['id'] = 'another_archive'
        duplicate['fallbackCandidateId'] = original['candidateLocationIds'][0]
        catalog['treasures'].append(duplicate)
        campaign = TreasureCampaign(catalog, 1)
        first = campaign.resolve(original['id'])
        other = original['candidateLocationIds'][1]
        before = campaign.export_state()
        with self.assertRaises(ResolutionError):
            campaign.resolve(duplicate['id'], unavailable_candidate_ids=[other])
        self.assertEqual(before, campaign.export_state())
        # Valid authored fallback is allowed only if it also passes occupancy.
        duplicate['candidateLocationIds'] = [other]
        campaign = TreasureCampaign(catalog, 1)
        self.assertEqual(first['candidateLocationId'], campaign.resolve(duplicate['id'], unavailable_candidate_ids=[other])['candidateLocationId'])
        duplicate['fallbackCandidateId'] = 'cand_mali_timbuktu'
        with self.assertRaises(TreasureError):
            validate_catalog(catalog)

    def test_malformed_resolution_never_mutates_source(self):
        campaign = TreasureCampaign(self.catalog, 4)
        tid = self.catalog['treasures'][0]['id']
        campaign.resolve(tid)
        state = campaign.export_state()
        for field, value in [('candidateLocationId', 'missing'), ('physicalMapId', 'pacific'),
                             ('rewardVariantId', 'missing'), ('guardId', 'missing'), ('outcomes', [])]:
            malformed = copy.deepcopy(state)
            malformed['resolved'][tid][field] = value
            source = copy.deepcopy(malformed)
            with self.assertRaises(TreasureError):
                TreasureCampaign(self.catalog, 4, malformed)
            self.assertEqual(source, malformed)
        for field in ('knowledge', 'collectionCounts'):
            incomplete = copy.deepcopy(state)
            incomplete[field].clear()
            with self.assertRaises(TreasureError):
                TreasureCampaign(self.catalog, 4, incomplete)
        state['campaignSeed'] = '1'
        with self.assertRaises(TreasureError):
            TreasureCampaign(self.catalog, 4, state)

    def test_exposed_or_collected_state_requires_consistent_committed_identity(self):
        campaign = TreasureCampaign(self.catalog, 4)
        tid = self.catalog['treasures'][0]['id']
        state = campaign.export_state()
        state['knowledge'][tid] = 'exact'
        with self.assertRaises(TreasureError):
            TreasureCampaign(self.catalog, 4, state)
        campaign.resolve(tid)
        state = campaign.export_state()
        state['knowledge'][tid] = 'collected'
        with self.assertRaises(TreasureError):
            TreasureCampaign(self.catalog, 4, state)

    def test_unbound_legacy_state_does_not_drop_recorded_knowledge(self):
        state = {"version": 1, "campaignSeed": "", "seedFingerprint": "", "resolved": {},
                 "knowledge": {self.catalog['treasures'][0]['id']: 'exact'}, "collectionCounts": {}}
        source = copy.deepcopy(state)
        with self.assertRaises(TreasureError):
            TreasureCampaign(self.catalog, 1, state)
        self.assertEqual(source, state)

    def test_weight_and_historical_fallback_contracts_fail_closed(self):
        for weight in (0, -1, True, 1_000_001):
            catalog = copy.deepcopy(self.catalog)
            catalog['candidateLocations'][0]['weight'] = weight
            with self.assertRaises(TreasureError):
                validate_catalog(catalog)
        catalog = copy.deepcopy(self.catalog)
        catalog['treasures'][0]['fallbackCandidateId'] = catalog['treasures'][1]['candidateLocationIds'][0]
        with self.assertRaises(TreasureError):
            validate_catalog(catalog)


if __name__ == '__main__':
    unittest.main()
