"""Headless conserved trade states executed through the live command registry."""
import copy
from pathlib import Path
import sys
import unittest

from test_playable_trade import fixtures, economy, trade

PROJECT = Path(__file__).resolve().parents[1]
VECTORS = PROJECT / 'wurst/MixedCargoVectorsTests.wurst'
STORES = ['personal', 'warehouse', 'ship']
LIVE = dict(personal='player_ship_hold', warehouse='warehouse:lisbon', ship='cargo:english_patrol_ship')


def mixed_catalogs():
    tc, ec, es = fixtures()
    goods = ['grain', 'tools']
    tc['goods'] = [dict(id=g, name=g, quantityUnitsPerDisplayUnit=1, basePriceMinor=p,
                        priceElasticityPermille=1000) for g, p in zip(goods, [10, 30])]
    ec['goods'] = [dict(id=g, quantityUnitsPerDisplayUnit=1, itemTypeId=g+'_cargo') for g in goods]
    ec['stores'] = []
    ec['markets'] = []
    es['storeBalances'] = []
    tc['marketRules'] = []
    for ident, kind, capacity, money in [('lisbon', 'settlement', 1000, 20000),
                                        ('london', 'settlement', 1000, 20000),
                                        ('personal', 'personal', 8, 1000),
                                        ('warehouse', 'warehouse', 6, 1000),
                                        ('ship', 'ship', 4, 0)]:
        owner = dict(kind='settlement', id='lisbon')
        if kind == 'personal':
            # Use the headless player store kind; the live portable hold is personal.
            kind = 'personal_inventory'
            owner = dict(kind='character', id='p1')
        elif kind == 'ship':
            owner = dict(kind='strategic_unit', id='ship')
        ec['stores'].append(dict(id=ident, kind=kind, owner=owner,
                                 capacityUnits=capacity, allowedGoodIds=goods.copy()))
        es['storeBalances'].append(dict(id=ident, storeId=ident,
            goods=[dict(goodId=g, quantityUnits=100) for g in goods] if ident in ('lisbon', 'london') else [],
            currencies=[dict(currencyId='coin', amountMinor=money)] if money else []))
        if ident in ('lisbon', 'london'):
            ec['markets'].append(dict(id=ident, storeId=ident, owner=owner))
            tc['marketRules'].append(dict(marketId=ident, currencyId='coin', goodIds=goods.copy(),
                targetStockUnits=dict.fromkeys(goods, 100), spreadPermille=80,
                priceFloorPermille=350, priceCeilingPermille=4000))
    economy.validate_state(ec, es)
    return tc, ec, es, trade.initial_state()


def amount(es, store, kind, good):
    b = next(b for b in es['storeBalances'] if b['id'] == store)
    key, qty = ('goodId', 'quantityUnits') if kind == 'goods' else ('currencyId', 'amountMinor')
    return next((v[qty] for v in b[kind] if v[key] == good), 0)


def vector_state(es, ts):
    result = ''
    lots = ts.get('players', {}).get('p1', {}).get('lots', [])
    for store in STORES:
        values = [amount(es, store, 'goods', g) for g in ('grain', 'tools')]
        values += [amount(es, store, 'currencies', 'coin')]
        values += [sum(l['costMinor'] for l in lots if l['storeId'] == store and l['goodId'] == g)
                   for g in ('grain', 'tools')]
        result += ','.join(map(str, values)) + ';'
    for market in ('lisbon', 'london'):
        result += ','.join(map(str, [amount(es, market, 'goods', 'grain'),
                                     amount(es, market, 'goods', 'tools'),
                                     amount(es, market, 'currencies', 'coin')])) + ';'
    return result


def actions(reverse):
    purchases = [('buy', 'personal', 'grain', 3, 'lisbon'),
                 ('buy', 'personal', 'tools', 2, 'lisbon')]
    moves = [('move', 'personal', 'grain', 2, 'warehouse'),
             ('move', 'personal', 'tools', 1, 'warehouse'),
             ('move', 'warehouse', 'grain', 1, 'ship'),
             ('move', 'personal', 'tools', 1, 'ship')]
    sales = [('sell', 'warehouse', 'tools', 1, 'lisbon'),
             ('sell', 'personal', 'grain', 1, 'london'),
             ('sell', 'ship', 'grain', 1, 'london'),
             ('sell', 'warehouse', 'grain', 1, 'lisbon'),
             ('sell', 'ship', 'tools', 1, 'london')]
    return purchases + moves + (list(reversed(sales)) if reverse else sales)


def vector_source():
    source = '''package MixedCargoVectorsTests
import MixedCargoTests

// Generated by tests/test_mixed_cargo.py --write-vectors. Every expected balance,
// market stock, currency and remaining acquisition cost comes from economy/trade.
'''
    for reverse in (False, True):
        tc, ec, es, ts = mixed_catalogs()
        source += f'\n@test function registeredMixedCargoOracleOrder{int(reverse)}()\n\tlet f=mixedTradeFixture()\n'
        total_cost = allocated = 0
        for i, (side, store, good, quantity, target) in enumerate(actions(reverse)):
            previous_cost = sum(l['costMinor'] for l in ts.get('players', {}).get('p1', {}).get('lots', []))
            if side == 'move':
                es, ts = trade.transfer_cargo(ec, es, ts, 'p1', f'move{i}', good, quantity, store, target)
                source += f'\tf.dispatch("/trade move {LIVE[store]} {LIVE[target]} {good} {quantity}")\n'
                source += '\tf.ports.output.assertEquals("Cargo moved.")\n'
            else:
                conditions = dict(shortagePermille=2000) if target == 'london' else None
                result = trade.execute(tc, ec, es, ts, dict(id=f'{side}{i}', playerId='p1',
                    marketId=target, storeId=store, goodId=good, side=side, quantityUnits=quantity), conditions)
                es, ts = result.economy_state, result.trade_state
                source += f'\tf.actors.moveTo(f.rpg.interactions.get("{target}"))\n'
                source += f'\tf.vessels.moveTo(f.rpg.interactions.get("{target}"))\n'
                source += f'\tf.dispatch("/trade select {target} {good}")\n'
                source += f'\tf.dispatch("/trade store {LIVE[store]}")\n'
                source += f'\tf.dispatch("/trade {side} {quantity}")\n'
                if side == 'buy':
                    total_cost += result.amount_minor
                else:
                    allocated += previous_cost - sum(l['costMinor'] for l in ts['players']['p1']['lots'])
            source += f'\tmixedCargoVectorState(f).assertEquals("{vector_state(es, ts)}")\n'
            assert sum(amount(es, b['id'], 'currencies', 'coin') for b in es['storeBalances']) == 42000
            for g in ('grain', 'tools'):
                assert sum(amount(es, b['id'], 'goods', g) for b in es['storeBalances']) == 200
        assert allocated == total_cost == 94
        assert not ts['players']['p1']['lots']
        source += '\tf.trade.controller.provenance.count.assertEquals(0)\n'
        source += '\tf.trade.controller.processedCount.assertEquals(11)\n'
        source += '\tf.trade.nextTransaction.assertEquals(12)\n'
    return source


class MixedCargoTests(unittest.TestCase):
    def test_registered_live_vectors_match_headless_quantities_currency_and_fifo_costs(self):
        self.assertEqual(VECTORS.read_text(), vector_source())

    def test_headless_capacity_compatibility_quantity_and_replay_are_atomic(self):
        tc, ec, es, ts = mixed_catalogs()
        for i, g in enumerate(('grain', 'tools')):
            result = trade.execute(tc, ec, es, ts, dict(id=f'b{i}', playerId='p1', marketId='lisbon',
                goodId=g, side='buy', quantityUnits=3 if g == 'grain' else 2, storeId='personal'))
            es, ts = result.economy_state, result.trade_state
        for good, quantity, dest, error in [('grain', 4, 'warehouse', 'insufficient'),
                                            ('tools', 1, 'warehouse', 'incompatible'),
                                            ('grain', 2, 'ship', 'capacity')]:
            rejected = copy.deepcopy(ec)
            if error == 'incompatible':
                next(s for s in rejected['stores'] if s['id'] == dest)['allowedGoodIds'] = ['grain']
            if error == 'capacity':
                next(s for s in rejected['stores'] if s['id'] == dest)['capacityUnits'] = 1
            before = copy.deepcopy((es, ts))
            with self.assertRaisesRegex(economy.EconomyError, error):
                trade.transfer_cargo(rejected, es, ts, 'p1', 'reject', good, quantity, 'personal', dest)
            self.assertEqual(before, (es, ts))
        before = copy.deepcopy((es, ts))
        with self.assertRaisesRegex(economy.EconomyError, 'capacity'):
            trade.execute(tc, ec, es, ts, dict(id='full', playerId='p1', marketId='lisbon',
                goodId='tools', side='buy', quantityUnits=4, storeId='personal'))
        self.assertEqual(before, (es, ts))
        moved, lots = trade.transfer_cargo(ec, es, ts, 'p1', 'once', 'grain', 2, 'personal', 'warehouse')
        with self.assertRaisesRegex(economy.EconomyError, 'already processed'):
            trade.transfer_cargo(ec, moved, lots, 'p1', 'once', 'tools', 1, 'personal', 'warehouse')
        self.assertEqual(2, amount(moved, 'personal', 'goods', 'tools'))
        self.assertEqual(64, sum(l['costMinor'] for l in lots['players']['p1']['lots'] if l['goodId'] == 'tools'))


if __name__ == '__main__':
    if '--write-vectors' in sys.argv:
        VECTORS.write_text(vector_source())
    else:
        unittest.main()
